def missing_ltspice_data():
    """Bu makinede olmayan LTspice verileri; koşullar öldüren testlerin kendi atlama koşullarıyla aynıdır."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))   # başka bir kopyanın kurulu paketi okunmasın
    from ltspice_llm import ReferenceDocs, ltspice_data_dir

    data = ltspice_data_dir()
    missing = set()
    if data is None or not (data / "lib" / "sym").is_dir():
        missing.add(SYMBOLS)
    if not ReferenceDocs().available:
        missing.add(REFERENCE)
    return missing


def split_by_ltspice_data(mutants, missing):
    """``(koşulacaklar, atlananlar)``: atlanan mutantın gerektirdiği veri ``missing`` içindedir."""
    run = [m for m in mutants if NEEDS_LTSPICE_DATA.get(m[3]) not in missing]
    return run, [m for m in mutants if NEEDS_LTSPICE_DATA.get(m[3]) in missing]


def make_copy():
    work = Path(tempfile.mkdtemp(prefix="ltspice_mutant_"))
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc", "*.asc", ".state", ".hypothesis")
    for d in COPY_DIRS:
        shutil.copytree(ROOT / d, work / d, ignore=ignore)
    for f in COPY_FILES:
        (work / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / f, work / f)
    return work


def run_tests(work, tests):
    env = dict(os.environ, LTSPICE_EXE=str(work / "nonexistent-ltspice" / "LTspice.exe"), PYTHONIOENCODING="utf-8")
    cmd = [sys.executable, "-m", "pytest", *tests, "-x", "-q", "-rf", "-p", "no:cacheprovider", "--tb=no"]
    proc = subprocess.run(cmd, cwd=work, env=env, capture_output=True, text=True, encoding="utf-8",
                          errors="replace", timeout=300, check=False)
    lines = [ln for ln in proc.stdout.splitlines() if ln.strip()]
    failed = next((ln.split(" ")[1] for ln in lines if ln.startswith("FAILED")), "")
    return proc.returncode, (lines[-1] if lines else proc.stderr.strip()[-200:]), failed


def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    argv = sys.argv[1:] if argv is None else argv
    selected = [m for m in MUTANTS if not argv or any(a in m[0] or a in m[3] for a in argv)]
    selected, skipped = split_by_ltspice_data(selected, missing_ltspice_data())
    for path, _old, _new, label, _tests in skipped:
        print(f"ATLANDI {path:<30} {label}: {NEEDS_LTSPICE_DATA[label]} bu makinede yok")
    note = f", {len(skipped)} atlandı" if skipped else ""
    if not selected:
        print(f"0/0 mutant öldü{note}")
        return 0

    base = make_copy()
    all_tests = sorted({t for m in selected for t in m[4]})
    code, last, _ = run_tests(base, all_tests)
    shutil.rmtree(base, ignore_errors=True)
    print(f"kopyada mutantsız: {last}")
    if code != 0:
        print("Mutantsız kopyada testler kırık; önce onları düzelt.")
        return 1

    bad = 0
    for path, old, new, label, tests in selected:
        work = make_copy()
        target = work / path
        text = target.read_text(encoding="utf-8")
        if text.count(old) != 1:
            bad += 1
            print(f"ESKİ   {path:<30} {label}: değiştirilecek metin {text.count(old)} kez bulundu (katalog güncel değil)")
            shutil.rmtree(work, ignore_errors=True)
            continue
        target.write_text(text.replace(old, new), encoding="utf-8")
        t0 = time.time()
        code, last, failed = run_tests(work, tests)
        shutil.rmtree(work, ignore_errors=True)
        killed = code != 0
        bad += not killed
        who = f" <- {failed}" if failed else ""
        print(f"{'ÖLDÜ ' if killed else 'SAĞ  '}  {path:<30} {label} ({time.time() - t0:.1f} sn){who}")
    print(f"{len(selected) - bad}/{len(selected)} mutant öldü{note}" + ("" if not bad else f", {bad} sorunlu"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
